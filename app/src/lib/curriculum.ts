export function getDefaultTermForSubject(subjectName: string, gradeLevel: string | number): 1 | 2 | 3 | 'all' | 'none' {
    const gl = String(gradeLevel || '').toLowerCase().trim();
    const gNum = parseInt(gl.replace(/\D/g, '')) || 0;
    
    // Elementary (Kinder, Grades 1-6) and Junior High School (Grades 7-10)
    // NEVER have semesters or trimesters — ALL subjects are strictly offered for the full year ('all')
    const isSHS = gNum === 11 || gNum === 12 || gl.includes('11') || gl.includes('12');
    if (!isSHS) {
        return 'all';
    }

    // For Grade 12, elective/specialized subjects default to 'none' (user chooses offering term manually)
    if (gNum === 12 || gl.includes('12')) {
        return 'none';
    }
    
    // DO 017, s. 2026 Table 3 & Table 10:
    // In Grade 11, BOTH Core subjects (160 hrs) AND Tech-Pro Electives (320 hrs) are offered across all 3 terms ('all').
    if (isGrade11CoreSubject(subjectName) || isGrade11TechProElective(subjectName)) {
        return 'all';
    }
    
    // Academic Electives in Grade 11 (80 hrs) are 1-term offerings chosen by the adviser.
    return 'none';
}

/** Converts every persisted schedule representation into a canonical term list. */
export function normalizeOfferedTerms(value: unknown): (1 | 2 | 3)[] {
    if (value === 'all') return [1, 2, 3];
    if (value === 'none' || value === undefined || value === null) return [];

    const entries = Array.isArray(value)
        ? value
        : typeof value === 'string' && value.includes(',')
            ? value.split(',')
            : [value];
    const terms = entries
        .map((entry) => Number(entry))
        .filter((entry): entry is 1 | 2 | 3 => entry === 1 || entry === 2 || entry === 3);
    return Array.from(new Set(terms)).sort((a, b) => a - b) as (1 | 2 | 3)[];
}

/**
 * Resolves the offered terms for a subject in a section.
 * In Senior High School (Grades 11 & 12), some electives are modular single-term subjects (e.g. Term 1, 2, or 3),
 * while Core subjects run across all terms.
 * For Elementary and Junior High School, all subjects run across all terms [1, 2, 3].
 */
export function resolveSubjectOfferedTerms(
    sub: { subject_name: string; term?: string | number | null; offered_terms?: (1 | 2 | 3)[]; id?: string },
    sectionObj?: { id?: string; section_grade_level?: string; section_metadata?: Record<string, unknown> } | null,
    hasGradesInTerm?: (termNum: number) => boolean
): number[] {
    const gradeLevel = sectionObj?.section_grade_level || '';
    const gradeNum = parseInt(gradeLevel.replace(/\D/g, '')) || 0;
    const isSHS = gradeNum === 11 || gradeNum === 12 || gradeLevel.toLowerCase().includes('11') || gradeLevel.toLowerCase().includes('12');

    // Elementary and JHS run all year
    if (!isSHS) {
        return [1, 2, 3];
    }

    // Grade 11 SSHS core learning areas and Tech-Pro electives are full-year offerings.
    if (gradeNum === 11 && (isGrade11CoreSubject(sub.subject_name) || isGrade11TechProElective(sub.subject_name))) {
        const subjectTermsMeta = (sectionObj?.section_metadata as Record<string, unknown> | undefined)?.subjectTerms as Record<string, unknown> | undefined;
        if (subjectTermsMeta && subjectTermsMeta[sub.subject_name] !== undefined) {
            return normalizeOfferedTerms(subjectTermsMeta[sub.subject_name]);
        }
        return [1, 2, 3];
    }

    // 1. Check the section schedule explicitly configured by the adviser.
    const subjectTermsMeta = (sectionObj?.section_metadata as Record<string, unknown> | undefined)?.subjectTerms as Record<string, unknown> | undefined;
    if (subjectTermsMeta) {
        const override = subjectTermsMeta[sub.subject_name];
        if (override !== undefined) {
            return normalizeOfferedTerms(override);
        }
    }

    // 2. Check an explicit multi-term schedule saved on the subject record.
    if (sub.offered_terms !== undefined) {
        return normalizeOfferedTerms(sub.offered_terms);
    }

    // 3. Check the legacy single-term setting saved on the subject record.
    const sTerm = sub.term;
    if (sTerm !== undefined && sTerm !== null) {
        return normalizeOfferedTerms(sTerm);
    }

    // 4. Grade 11 Core is the only automatic SSHS offering.  Every other
    // subject remains unscheduled until the adviser decides its term(s).
    const defTerm = getDefaultTermForSubject(sub.subject_name, gradeLevel);
    if (defTerm !== 'none') return normalizeOfferedTerms(defTerm);

    // 5. Smart check: If hasGradesInTerm callback is provided, check which quarters actually have non-zero grades
    if (hasGradesInTerm) {
        const activeTerms = [1, 2, 3].filter(t => hasGradesInTerm(t));
        if (activeTerms.length > 0 && activeTerms.length < 3) {
            return activeTerms;
        }
    }

    return [];
}

