/**
 * Computes the units per term and total year units for an SHS subject based on DepEd Order No. 017, s. 2026 Annex E (Table 19).
 */
export interface ShsSubjectUnitInfo {
    unitsPerTerm: number;
    yearUnits: number;
    category: 'core' | 'academic_elective' | 'arts_elective' | 'techpro_elective' | 'work_immersion';
}

export function getShsSubjectUnitInfo(subjectName: string, gradeLevel: string): ShsSubjectUnitInfo {
    const gl = (gradeLevel || '').toLowerCase();
    const isG11 = gl.includes('11');
    const norm = (subjectName || '').trim().toLowerCase();

    // 1. Grade 11 Core Subjects: 160 hrs across 3 terms = 2 units per term, 6 units per year
    const g11Cores = [
        'effective communication',
        'mabisang komunikasyon',
        'general mathematics',
        'general science',
        'life and career skills',
        'pag-aaral ng kasaysayan at lipunang pilipino',
        'kasaysayan at lipunang pilipino'
    ];
    if (isG11 && g11Cores.some(c => norm.includes(c))) {
        return { unitsPerTerm: 2, yearUnits: 6, category: 'core' };
    }

    // 2. Arts Electives (160 hours in one term = 6 units)
    if (norm.includes('arts apprenticeship') || norm.includes('creative production and presentation') || norm.includes('in-campus field exposure for sports')) {
        return { unitsPerTerm: 6, yearUnits: 6, category: 'arts_elective' };
    }

    // 3. Work Immersion (Grade 12: 320 hours in one term = 12 units)
    if (norm.includes('work immersion')) {
        return { unitsPerTerm: 12, yearUnits: 12, category: 'work_immersion' };
    }

    // 4. Tech-Pro Electives:
    // Grade 11: 320 hours across 3 terms = 4 units per term, 12 units per year
    // Grade 12: 320 hours in one term = 12 units per term, 12 units per year
    const techPros = [
        'aesthetic services', 'aesthethic services', 'aesthetic', 'aesthethic', 'beauty care', 'barbering services', 'caregiving', 'hairdressing', 'wellness services', 'hilot',
        'agricultural crops', 'agro-entrepreneurship', 'aquaculture', 'fish capture', 'food processing',
        'organic agriculture', 'poultry production', 'ruminants production', 'swine production', 'garments artisanry',
        'handicrafts', 'weaving', 'automotive servicing', 'electrical repair', 'engine and chassis', 'driving',
        'motorcycle', 'small engine', 'carpentry', 'construction operation', 'manual metal arc welding', 'welding',
        'technical drafting', 'animation', 'illustration', 'visual graphics', 'visual graphic', 'bakery operation', 'bakery operations',
        'events management', 'food and beverage', 'hotel operation', 'hotel operations', 'front office', 'housekeeping', 'kitchen operations',
        'kitchen operation', 'tourism services', 'commercial air-conditioning', 'domestic refrigeration',
        'electrical installation', 'electronics product', 'mechatronics', 'photovoltaic systems', 'broadband installation',
        'computer programming', 'java', '.net', 'oracle', 'computer systems servicing', 'contact center', 'marine engineering',
        'marine transportation', 'support level', 'ships catering'
    ];

    if (techPros.some(tp => norm.includes(tp))) {
        if (isG11) {
            return { unitsPerTerm: 4, yearUnits: 12, category: 'techpro_elective' };
        }
        return { unitsPerTerm: 12, yearUnits: 12, category: 'techpro_elective' };
    }

    // 5. Standard Academic Electives (80 hours per term = 3 units per term, 3 units per year)
    return { unitsPerTerm: 3, yearUnits: 3, category: 'academic_elective' };
}

/**
 * DepEd Order No. 017, s. 2026 Table 7: Maximum Class Size for SSHS Classes
 */
export const SSHS_CLASS_SIZE_LIMITS = {
    core: 40,
    techpro: 25,
    academic: 30
};

export function getClassSizeLimit(subjectName: string, gradeLevel: string): { maxStudents: number; category: 'core' | 'techpro' | 'academic'; categoryLabel: string } {
    const gl = (gradeLevel || '').toLowerCase();
    const isSHS = gl.includes('11') || gl.includes('12');
    
    if (!isSHS) {
        return { maxStudents: 45, category: 'core', categoryLabel: 'Standard Class Size' };
    }

    const unitInfo = getShsSubjectUnitInfo(subjectName, gradeLevel);
    if (unitInfo.category === 'core') {
        return { maxStudents: SSHS_CLASS_SIZE_LIMITS.core, category: 'core', categoryLabel: 'Core Subject (DO 017 Max 40)' };
    }
    if (unitInfo.category === 'techpro_elective' || unitInfo.category === 'work_immersion') {
        return { maxStudents: SSHS_CLASS_SIZE_LIMITS.techpro, category: 'techpro', categoryLabel: 'Tech-Pro Elective (DO 017 Max 25)' };
    }
    return { maxStudents: SSHS_CLASS_SIZE_LIMITS.academic, category: 'academic', categoryLabel: 'Academic Elective (DO 017 Max 30)' };
}

